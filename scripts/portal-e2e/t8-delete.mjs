import { api, adminToken, check, customer, db, describe, summary } from "./lib.mjs"
const admin = await adminToken()
const A = (m, p, body) => api(m, p, { token: admin, body, store: false })
const RUN = Date.now().toString(36)
describe("Deleting an organisation")
const m = await customer(`del+${RUN}@club.example.com`)
let r = await A("POST", "/admin/organisations", { handle: `del-${RUN}`, name: "To delete", default_pricing_tier: "gold" })
const org = r.body.organisation ?? r.body
await A("POST", `/admin/organisations/${org.id}/members`, { customer_id: m.id, role: "owner" })
const tiers = async () => (await db.query(`select g.name from customer_group g join customer_group_customer x on x.customer_group_id=g.id where x.customer_id=$1 and x.deleted_at is null`, [m.id])).rows.map((x) => x.name)
check("member got Gold", (await tiers()).includes("Tier: Gold"), await tiers())
await api("POST", `/store/customers/me/organisations/${org.id}/invites`, { token: m.token, body: { email: `x+${RUN}@club.example.com`, role: "viewer" } })
r = await A("DELETE", `/admin/organisations/${org.id}`)
check("delete answers with what it cleaned", r.status === 200 && r.body.members_removed === 1 && r.body.invites_cancelled === 1, r.body)
check("Gold taken back", !(await tiers()).includes("Tier: Gold"), await tiers())
r = await api("GET", `/store/customers/me/organisations/${org.id}`, { token: m.token })
check("ex-member can no longer open it", r.status === 404, r.status)
r = await api("GET", "/store/customers/me/organisations", { token: m.token })
check("…and it's gone from their list", !JSON.stringify(r.body).includes(org.id), null)
process.exit(summary() ? 1 : 0)
